#!/usr/bin/env node
/**
 * Scans assets/music/ and (re)writes src/library/manifest.ts.
 *
 *   node scripts/build-manifest.js
 *
 * Metro (Expo's bundler) can only bundle files that are `require()`d with a
 * literal path, so the manifest has to be generated rather than read at runtime.
 * Existing valence/arousal tags in manifest.ts are kept; new files start at
 * 0 / 0 and are marked `untagged` so the Library screen asks you to place them.
 */
const fs = require('fs');
const path = require('path');

const MUSIC_DIR = path.join(__dirname, '..', 'assets', 'music');
const OUT = path.join(__dirname, '..', 'src', 'library', 'manifest.ts');
const EXT = new Set(['.mp3', '.m4a', '.wav', '.aac', '.ogg']);

const existing = {};
if (fs.existsSync(OUT)) {
  const src = fs.readFileSync(OUT, 'utf8');
  const re = /id:\s*'([^']+)'[\s\S]*?valence:\s*(-?[\d.]+)[\s\S]*?arousal:\s*(-?[\d.]+)[\s\S]*?tagged:\s*(true|false)/g;
  let m;
  while ((m = re.exec(src))) existing[m[1]] = { valence: +m[2], arousal: +m[3], tagged: m[4] === 'true' };
}

// tags.json (written by jen-seed-library.js, or by hand) places files on the map
const TAGS_FILE = path.join(MUSIC_DIR, 'tags.json');
const sidecar = fs.existsSync(TAGS_FILE) ? JSON.parse(fs.readFileSync(TAGS_FILE, 'utf8')) : {};

const files = fs.readdirSync(MUSIC_DIR).filter((f) => EXT.has(path.extname(f).toLowerCase())).sort();

const titleOf = (f) => path.basename(f, path.extname(f)).replace(/^\d+[-_ ]*/, '').replace(/[-_]+/g, ' ');

const lines = files.map((f) => {
  const id = path.basename(f, path.extname(f));
  const prev = existing[id] ?? (sidecar[id] ? { valence: sidecar[id].valence, arousal: sidecar[id].arousal, tagged: true } : undefined);
  const v = prev ? prev.valence : 0;
  const a = prev ? prev.arousal : 0;
  const tagged = prev ? prev.tagged : false;
  return `  {\n    id: '${id}',\n    title: '${titleOf(f).replace(/'/g, "\\'")}',\n    source: require('@/assets/music/${f}'),\n    mood: { valence: ${v}, arousal: ${a} },\n    tagged: ${tagged},\n  },`;
});

const out = `// GENERATED by scripts/build-manifest.js — edit tags here or in the Library screen.
// Run the script again after adding files to assets/music/.
import type { Mood } from '@/engine/spectrum';

export type ManifestTrack = {
  id: string;
  title: string;
  source: number;
  mood: Mood;
  tagged: boolean;
};

export const MANIFEST: ManifestTrack[] = [
${lines.join('\n')}
];
`;
fs.writeFileSync(OUT, out);
console.log(`manifest: ${files.length} track(s) → ${path.relative(process.cwd(), OUT)}`);
